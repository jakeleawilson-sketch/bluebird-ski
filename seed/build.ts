// Generates db/seed.sql from seed/data.ts. Idempotent (INSERT OR REPLACE for
// reference data, INSERT OR IGNORE for sources so admin toggles survive).
import { writeFileSync } from 'node:fs';
import { airports, countries, resorts, sources, transferCost, weeks } from './data';
import { slugify } from '../worker/lib/text';

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? '1' : '0';
  return `'${String(v).replace(/'/g, "''")}'`;
};

const fmtWeek = (iso: string) => {
  const d = new Date(iso + 'T12:00:00Z');
  return 'Sat ' + d.toLocaleDateString('en-GB', { day: 'numeric', month: 'short', timeZone: 'UTC' });
};

const out: string[] = ['-- GENERATED by seed/build.ts. Do not edit by hand.', ''];

countries.forEach(([code, name], i) =>
  out.push(`INSERT OR REPLACE INTO countries (code, name, sort_order) VALUES (${q(code)}, ${q(name)}, ${i + 1});`));

airports.forEach((a, i) =>
  out.push(`INSERT OR REPLACE INTO airports (iata, name, grp, sort_order) VALUES (${q(a.iata)}, ${q(a.name)}, ${q(a.grp)}, ${i + 1});`));

for (const w of weeks) {
  // Keep any admin un-hide: only insert if missing, then refresh label/badge.
  out.push(`INSERT OR IGNORE INTO weeks (start_date, label, hidden, badge) VALUES (${q(w.start)}, ${q(fmtWeek(w.start))}, ${q(!!w.hidden)}, ${q(w.badge ?? null)});`);
  out.push(`UPDATE weeks SET label = ${q(fmtWeek(w.start))}, badge = ${q(w.badge ?? null)} WHERE start_date = ${q(w.start)};`);
}

const ids = new Set<string>();
for (const r of resorts) {
  const id = slugify(r.name);
  if (ids.has(id)) throw new Error('duplicate resort id ' + id);
  ids.add(id);
  const cost = Object.fromEntries(Object.entries(r.tx).map(([k, m]) => [k, transferCost(m)]));
  out.push(
    `INSERT OR REPLACE INTO resorts (id, name, aliases, country_code, top_altitude_m, base_altitude_m, glacier, ski_area_km, nearest_airports, transfer_mins, transfer_cost_gbp) VALUES (` +
      [id, r.name, JSON.stringify(r.aliases ?? []), r.cc, r.top, r.base, !!r.glacier, r.km ?? null, JSON.stringify(Object.keys(r.tx)), JSON.stringify(r.tx), JSON.stringify(cost)].map(q).join(', ') +
      ');',
  );
}

for (const s of sources) {
  out.push(`INSERT OR IGNORE INTO sources (id, name, type, base_url, research_note) VALUES (${[s.id, s.name, s.type, s.base_url, s.note].map(q).join(', ')});`);
  out.push(`UPDATE sources SET name = ${q(s.name)}, base_url = ${q(s.base_url)}, research_note = ${q(s.note)} WHERE id = ${q(s.id)};`);
}

writeFileSync(new URL('../db/seed.sql', import.meta.url), out.join('\n') + '\n');
console.log(`seed.sql: ${countries.length} countries, ${airports.length} airports, ${weeks.length} weeks, ${resorts.length} resorts, ${sources.length} sources`);
